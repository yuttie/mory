// Generates src/hljs-language-map.ts: a map from every highlight.js language
// name and alias (lowercased) to the grammar module's file base name, so the
// markdown renderer can lazy-load only the grammars a document actually uses.
//
// Rerun after upgrading highlight.js:
//   npm run generate:hljs-language-map
import { readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const hljs = require('highlight.js/lib/core');

const frontendDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const languagesDir = join(frontendDir, 'node_modules/highlight.js/lib/languages');

const map = {};
for (const file of readdirSync(languagesDir).sort()) {
  // Skip the deprecation stubs (foo.js.js) shipped alongside each grammar.
  if (!file.endsWith('.js') || file.endsWith('.js.js')) {
    continue;
  }
  const name = file.slice(0, -'.js'.length);
  const definition = require(`highlight.js/lib/languages/${name}`)(hljs);
  map[name.toLowerCase()] = name;
  for (const alias of definition.aliases ?? []) {
    map[alias.toLowerCase()] = name;
  }
}

const version = require('highlight.js/package.json').version;
const entries = Object.keys(map)
  .sort()
  .map((alias) => `  '${alias}': '${map[alias]}',`)
  .join('\n');

const output = `\
// Generated by scripts/generate-hljs-language-map.mjs from highlight.js ${version}.
// Do not edit by hand; rerun \`npm run generate:hljs-language-map\` after
// upgrading highlight.js.

/**
 * Maps every highlight.js language name and alias (lowercased) to the base
 * name of its grammar module under highlight.js/es/languages/.
 */
export const hljsLanguageMap: Record<string, string> = {
${entries}
};
`;

const outPath = join(frontendDir, 'src/hljs-language-map.ts');
writeFileSync(outPath, output);
console.log(`Wrote ${Object.keys(map).length} entries to ${outPath}`);
